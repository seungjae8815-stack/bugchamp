/// 젤리 **소비 금액**을 보기 좋은 단위로 맞춘다(§2.6, 2026-08-31 확정).
///
/// 왜 필요한가: 젤리를 쓰는 자리 대부분이 시간·수량에 비례하는 공식이라,
/// 화면에 `13젤리` · `27젤리` 같은 값이 뜬다. 프리미엄 재화는 가격이 읽히는
/// 물건이어야 하고, 유저는 그 값이 계산기에서 나온 숫자인지 정해진 가격인지
/// 구분하지 못한다. 5·10 단위로 떨어지면 "가격표"로 읽힌다.
///
/// 규칙 — 큰 금액일수록 성긴 단위로:
/// - 5 미만: **5**(무료처럼 보이는 1~2젤리를 없앤다)
/// - 50 미만: 가장 가까운 **5**
/// - 50 이상: 가장 가까운 **10**
///
/// ⚠️ 올림이 아니라 **반올림**이다. 올림으로 하면 곡선이 조금만 올라가도
/// 다음 칸으로 튀어 체감 가격이 실제보다 비싸진다. 대신 0 으로 내려가지는
/// 않는다(공짜가 되면 소비처가 아니다).
///
/// ⚠️ **수입(보상)에는 쓰지 않는다.** 보상 젤리를 반올림하면 하루 수입이
/// 바뀌어 `jelly_sim` 결과가 통째로 어긋난다(§2.6 수도꼭지 규칙).
int roundJellyCost(num raw) {
  if (raw <= 0) return 0;
  if (raw < 5) return 5;
  final step = raw < 50 ? 5 : 10;
  final v = (raw / step).round() * step;
  return v < step ? step : v;
}
